const filteredSidebars: SidebarsConfig = {};

if (activeCustomer && Array.isArray(activeCustomer.allowedSidebars)) {
  activeCustomer.allowedSidebars.forEach(sidebarKey => {
    if (sidebars[sidebarKey]) {
      // Sidebar'ı eklemeden önce İÇERİĞİNİ filtrele
      const originalItems = sidebars[sidebarKey];

      // Autogenerated sidebarlar için farklı, manuel olanlar için farklı işlem yap
      if (Array.isArray(originalItems)) {
        filteredSidebars[sidebarKey] = filterSidebarItems(originalItems);
      } else {
        filteredSidebars[sidebarKey] = originalItems;
      }
    }
  });
}

export default filteredSidebars;
