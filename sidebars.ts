const CUSTOMER_ID = process.env.CUSTOMER_ID || 'payporter';
const activeCustomer = customers[CUSTOMER_ID] || customers['payporter'];
const excludedDocs = activeCustomer?.excludedDocs || [];

// Sidebar öğelerini derinlemesine filtreleyen fonksiyon
function filterSidebarItems(items: any[]) {
  return items
    .filter(item => {
      // 1. Öğe bir string (docId) ise
      if (typeof item === 'string') {
        // "money-transfers/to-card" ile başlayan her şeyi sil
        return !excludedDocs.some(excluded => item.startsWith(excluded));
      }

      // 2. Öğe bir object (category vb.) ise
      if (typeof item === 'object') {
        // Eğer kategorinin içindeki bir ID veya label senin listenle eşleşiyorsa sil
        const itemId = item.id || item.label?.toLowerCase().replace(/ /g, '-');
        if (itemId && excludedDocs.some(excluded => itemId.startsWith(excluded))) {
          return false;
        }
      }
      return true;
    })
    .map(item => {
      // Kategori içindekileri derinlemesine kontrol etmeye devam et
      if (typeof item === 'object' && item.items) {
        return {
          ...item,
          items: filterSidebarItems(item.items)
        };
      }
      return item;
    })
    // Boş kalan kategorileri temizle
    .filter(item => {
      if (typeof item === 'object' && item.type === 'category' && item.items && item.items.length === 0) {
        return false;
      }
      return true;
    });
}

